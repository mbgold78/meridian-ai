/**
 * PINNED hash vectors for the ADR-003 D14 agent governance mirror (engine-spec
 * agents.md §11; test plan #13; port-map trap #3: "a pinned hash-vector test
 * lands BEFORE enabling" — this suite is that gate; the mirror became a verb-
 * path default in the same 6b chunk).
 *
 * <p>The pinned constants were generated by running the frozen
 * {@link AgentGovernanceChainMirror} anchor layout through the (itself pinned
 * — {@code CanonicalJsonHashVectorTest}) {@code DecisionLogService}
 * canonical-JSON algorithm on the substrate toolchain (Java 21). Any change
 * to the anchor layout (title / description / metadata key set or insertion
 * order / status / type) breaks these constants — they must NEVER be
 * regenerated to make a failing test pass: existing engagement chains would
 * silently change meaning.
 *
 * <p>Layout semantics pinned here:
 * <ul>
 *   <li>Chain inputs are immutable identifiers ONLY ([DECISIONLOG-COVERAGE]):
 *       agent_key, row UUIDs, event type/seq, the stable actorMemberId,
 *       occurred_at, digests — never actor display LABELS.</li>
 *   <li>The DEPLOYED anchor carries {@code criteriaDigest} — §11's "canonical
 *       JSON includes criteria_digest" acceptance.</li>
 *   <li>The RETIRED anchor carries {@code retiredReason} (KILLED here) — kill
 *       and orderly retirement are both chain-anchored.</li>
 *   <li>Anchors chain GENESIS → A → B → C inside the domain and re-verify
 *       green ({@code verifyChain}); the hash writes back to
 *       {@code agent_status_events.decision_log_hash} (cross-navigation).</li>
 * </ul>
 */
class AgentMirrorHashVectorTest {

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private static final String DOMAIN_ID = "5d3c0e6a-71d2-4e5b-9a64-3f8a2b1c9d70";
    private static final String REG_ID = "2a9f4c1e-8b3d-4e6f-9a0b-1c2d3e4f5a6b";
    private static final String MEMBER_ID = "9e8d7c6b-5a4f-4e3d-9c1b-0a9f8e7d6c5b";
    private static final String EVENT_DEPLOYED = "11111111-1111-4111-8111-111111111111";
    private static final String EVENT_PROMOTED = "22222222-2222-4222-8222-222222222222";
    private static final String EVENT_KILLED = "33333333-3333-4333-8333-333333333333";
    private static final String REVIEW_ID = "44444444-4444-4444-8444-444444444444";
    private static final String CRITERIA_DIGEST =
            "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";
    private static final String AGENT_KEY = "a-msg-router";

    // ---- Pinned vector A: DEPLOYED anchor (criteria digest), GENESIS link ----
    private static final String EXPECTED_JSON_DEPLOYED =
            "{\"decisionType\":\"AGENT_DEPLOYED\","
            + "\"description\":\"Agent a-msg-router deployed with a frozen mandate; criteria"
            + " digest anchored (ADR-003 D5/D14).\","
            + "\"domainId\":\"" + DOMAIN_ID + "\","
            + "\"metadata\":{\"anchor\":\"AGENT_DEPLOYED\",\"agentRegistrationId\":\"" + REG_ID
            + "\",\"agentKey\":\"" + AGENT_KEY + "\",\"eventId\":\"" + EVENT_DEPLOYED
            + "\",\"eventType\":\"DEPLOYED\",\"eventSeq\":1,\"actorMemberId\":\"" + MEMBER_ID
            + "\",\"criteriaDigest\":\"" + CRITERIA_DIGEST
            + "\",\"occurredAt\":\"2026-06-11T00:00:00Z\"},"
            + "\"previousHash\":\"GENESIS\","
            + "\"status\":\"APPROVED\","
            + "\"title\":\"agent:a-msg-router:AGENT_DEPLOYED\"}";
    private static final String EXPECTED_HASH_DEPLOYED =
            "9dc1a243b4ec944219f7c31a58970662dc7f0c99e82eb085fe711d46a2e1ed74";

    // ---- Pinned vector B: PROMOTED anchor (consumed review id), links to A ----
    private static final String EXPECTED_JSON_PROMOTED =
            "{\"decisionType\":\"AGENT_PROMOTED\","
            + "\"description\":\"Agent a-msg-router promoted shadow to live against a consumed"
            + " APPROVED promotion review (ADR-003 D10/D14).\","
            + "\"domainId\":\"" + DOMAIN_ID + "\","
            + "\"metadata\":{\"anchor\":\"AGENT_PROMOTED\",\"agentRegistrationId\":\"" + REG_ID
            + "\",\"agentKey\":\"" + AGENT_KEY + "\",\"eventId\":\"" + EVENT_PROMOTED
            + "\",\"eventType\":\"PROMOTED\",\"eventSeq\":2,\"actorMemberId\":\"" + MEMBER_ID
            + "\",\"consumedReviewId\":\"" + REVIEW_ID
            + "\",\"occurredAt\":\"2026-06-11T01:00:00Z\"},"
            + "\"previousHash\":\"" + EXPECTED_HASH_DEPLOYED + "\","
            + "\"status\":\"APPROVED\","
            + "\"title\":\"agent:a-msg-router:AGENT_PROMOTED\"}";
    private static final String EXPECTED_HASH_PROMOTED =
            "222fc08640d34f6b01cea21179e3f9e908c077df7426d47428d7c8c7b35abf59";

    // ---- Pinned vector C: RETIRED anchor (retiredReason=KILLED), links to B ----
    private static final String EXPECTED_JSON_RETIRED =
            "{\"decisionType\":\"AGENT_RETIRED\","
            + "\"description\":\"Agent a-msg-router reached the terminal-absorbing retired state;"
            + " termination is chain-anchored either way (ADR-003 D4/D14).\","
            + "\"domainId\":\"" + DOMAIN_ID + "\","
            + "\"metadata\":{\"anchor\":\"AGENT_RETIRED\",\"agentRegistrationId\":\"" + REG_ID
            + "\",\"agentKey\":\"" + AGENT_KEY + "\",\"eventId\":\"" + EVENT_KILLED
            + "\",\"eventType\":\"KILLED\",\"eventSeq\":3,\"actorMemberId\":\"" + MEMBER_ID
            + "\",\"retiredReason\":\"KILLED\","
            + "\"occurredAt\":\"2026-06-11T02:00:00Z\"},"
            + "\"previousHash\":\"" + EXPECTED_HASH_PROMOTED + "\","
            + "\"status\":\"APPROVED\","
            + "\"title\":\"agent:a-msg-router:AGENT_RETIRED\"}";
    private static final String EXPECTED_HASH_RETIRED =
            "815e5fb9ce69a064d81cdf373b6891681e650fff5c8b94eb143bddff7461850d";

    private DesignDecisionRepository decisionRepository;
    private AgentStatusEventRepository eventRepository;
    private DecisionLogService decisionLogService;
    private AgentGovernanceChainMirror mirror;
    private List<DesignDecision> chain;
    private List<AgentStatusEvent> writtenBack;

    @BeforeEach
    void setUp() {
        decisionRepository = mock(DesignDecisionRepository.class);
        eventRepository = mock(AgentStatusEventRepository.class);
        PlatformTransactionManager txManager = mock(PlatformTransactionManager.class);
        when(txManager.getTransaction(any())).thenReturn(new SimpleTransactionStatus());
        chain = new ArrayList<>();
        writtenBack = new ArrayList<>();
        when(decisionRepository.save(any(DesignDecision.class))).thenAnswer(inv -> {
            DesignDecision d = inv.getArgument(0);
            chain.add(d);
            return d;
        });
        when(decisionRepository.findByDomainId(UUID.fromString(DOMAIN_ID)))
                .thenAnswer(inv -> new ArrayList<>(chain));
        when(eventRepository.save(any(AgentStatusEvent.class))).thenAnswer(inv -> {
            AgentStatusEvent e = inv.getArgument(0);
            writtenBack.add(e);
            return e;
        });
        decisionLogService = new DecisionLogService(decisionRepository, new ObjectMapper(), txManager);
        mirror = new AgentGovernanceChainMirror(decisionLogService, eventRepository,
                MAPPER, txManager);
    }

    /**
     * The full deploy → promote → kill sequence reproduces the pinned chain
     * GENESIS → A → B → C byte-for-byte (no transaction active here ⇒ the
     * mirror appends immediately); the chain re-verifies green; every hash
     * writes back to its event's {@code decision_log_hash}.
     */
    @Test
    void deployPromoteKillSequenceReproducesThePinnedChain() {
        AgentRegistration reg = registration();
        AgentStatusEvent deployed = event(EVENT_DEPLOYED, AgentEventType.DEPLOYED, 1,
                "2026-06-11T00:00:00Z");
        AgentStatusEvent promoted = event(EVENT_PROMOTED, AgentEventType.PROMOTED, 2,
                "2026-06-11T01:00:00Z");
        AgentStatusEvent killed = event(EVENT_KILLED, AgentEventType.KILLED, 3,
                "2026-06-11T02:00:00Z");
        when(eventRepository.findById(UUID.fromString(EVENT_DEPLOYED)))
                .thenReturn(Optional.of(deployed));
        when(eventRepository.findById(UUID.fromString(EVENT_PROMOTED)))
                .thenReturn(Optional.of(promoted));
        when(eventRepository.findById(UUID.fromString(EVENT_KILLED)))
                .thenReturn(Optional.of(killed));

        mirror.onDeployed(reg, deployed);
        reg.setRetiredReason(AgentRetiredReason.KILLED);
        mirror.onPromoted(reg, promoted, UUID.fromString(REVIEW_ID));
        mirror.onRetired(reg, killed);

        assertThat(chain).hasSize(3);
        // currentHash equality IS the canonical-JSON byte pin: the hash is
        // SHA-256 over those exact bytes (algorithm itself pinned by
        // CanonicalJsonHashVectorTest), and pinnedHashesAgreeWithIndependentDigest
        // proves the pinned constants are the digests of the pinned JSON.
        assertThat(chain.get(0).getCurrentHash()).isEqualTo(EXPECTED_HASH_DEPLOYED);
        assertThat(chain.get(1).getCurrentHash()).isEqualTo(EXPECTED_HASH_PROMOTED);
        assertThat(chain.get(2).getCurrentHash()).isEqualTo(EXPECTED_HASH_RETIRED);

        // GET /decision-log/verify semantics stay green over the agent anchors
        assertThat(decisionLogService.verifyChain(UUID.fromString(DOMAIN_ID)).valid()).isTrue();

        // §11 cross-navigation: each hash wrote back to its event row
        assertThat(deployed.getDecisionLogHash()).isEqualTo(EXPECTED_HASH_DEPLOYED);
        assertThat(promoted.getDecisionLogHash()).isEqualTo(EXPECTED_HASH_PROMOTED);
        assertThat(killed.getDecisionLogHash()).isEqualTo(EXPECTED_HASH_RETIRED);
    }

    /** The pinned hashes agree with an INDEPENDENT SHA-256 over the pinned JSON bytes. */
    @Test
    void pinnedHashesAgreeWithIndependentDigest() throws Exception {
        assertThat(sha256Hex(EXPECTED_JSON_DEPLOYED)).isEqualTo(EXPECTED_HASH_DEPLOYED);
        assertThat(sha256Hex(EXPECTED_JSON_PROMOTED)).isEqualTo(EXPECTED_HASH_PROMOTED);
        assertThat(sha256Hex(EXPECTED_JSON_RETIRED)).isEqualTo(EXPECTED_HASH_RETIRED);
    }

    /** [DECISIONLOG-COVERAGE]: actor display labels never enter the chain inputs. */
    @Test
    void chainInputsCarryNoDisplayNames() {
        AgentRegistration reg = registration();
        AgentStatusEvent deployed = event(EVENT_DEPLOYED, AgentEventType.DEPLOYED, 1,
                "2026-06-11T00:00:00Z");
        when(eventRepository.findById(any())).thenReturn(Optional.of(deployed));
        mirror.onDeployed(reg, deployed);
        String chainInputs = chain.get(0).getTitle() + chain.get(0).getDescription()
                + chain.get(0).getMetadata().toString();
        assertThat(chainInputs).doesNotContain("Compliance Officer"); // the actor LABEL
        assertThat(chainInputs).contains(MEMBER_ID);                  // the stable id
    }

    // ------------------------------------------------------------------ fixtures

    private AgentRegistration registration() {
        AgentRegistration reg = new AgentRegistration();
        reg.setId(UUID.fromString(REG_ID));
        reg.setDomainId(UUID.fromString(DOMAIN_ID));
        reg.setAgentKey(AGENT_KEY);
        reg.setCriteriaDigest(CRITERIA_DIGEST);
        return reg;
    }

    private AgentStatusEvent event(String id, AgentEventType type, int seq, String occurredAt) {
        AgentStatusEvent event = new AgentStatusEvent();
        event.setId(UUID.fromString(id));
        event.setAgentRegistrationId(UUID.fromString(REG_ID));
        event.setDomainId(UUID.fromString(DOMAIN_ID));
        event.setEventType(type);
        event.setEventSeq(seq);
        event.setActorType(ContractActorType.HUMAN);
        event.setActorMemberId(UUID.fromString(MEMBER_ID));
        event.setActorLabel("Compliance Officer");
        event.setIdempotencyKey("vector:" + seq);
        event.setOccurredAt(Instant.parse(occurredAt));
        return event;
    }

    private static String sha256Hex(String input) throws Exception {
        MessageDigest digest = MessageDigest.getInstance("SHA-256");
        StringBuilder sb = new StringBuilder();
        for (byte b : digest.digest(input.getBytes(StandardCharsets.UTF_8))) {
            sb.append(String.format("%02x", b));
        }
        return sb.toString();
    }
}
