/**
 * PINNED hash vectors for the ADR-002 D14 contract-accountability mirror
 * (port-map trap #3: "a contract-transition hash-vector test is pinned BEFORE
 * enabling" — this suite is that gate; the mirror became the
 * {@code ContractEngineConfig} default in the same chunk).
 *
 * <p>The pinned constants were generated by computing SHA-256 over the exact
 * canonical-JSON bytes the frozen
 * {@link DecisionLogContractAccountabilityMirror} anchor layout produces
 * through the (itself pinned — {@code CanonicalJsonHashVectorTest})
 * {@code DecisionLogService.buildCanonicalJson} algorithm, standalone on the
 * substrate toolchain (Java 21). Any change to the anchor layout (title /
 * description / metadata key set or insertion order / status / type) breaks
 * these constants — they must NEVER be regenerated to make a failing test
 * pass: existing engagement chains would silently change meaning.
 *
 * <p>Layout semantics pinned here:
 * <ul>
 *   <li>Chain inputs are immutable identifiers ONLY: {@code contract_key},
 *       row UUIDs, period keys, actor id — never display titles or operator
 *       prose ([DECISIONLOG-COVERAGE]).</li>
 *   <li>title = {@code contract:<contractKey>:<anchor>}; decisionType =
 *       {@code CONTRACT_ACCOUNTABILITY}; status = {@code APPROVED}.</li>
 *   <li>metadata insertion order: anchor, contractId, contractKey,
 *       [breachId, periodKey?, resolutionActor? — waiver only], occurredAt
 *       (nested JsonNodes keep insertion order; only top-level keys sort).</li>
 *   <li>Anchors are bounded to ACTIVATED / DECLINED / BREACH_WAIVED and chain
 *       GENESIS → A → B → C within a domain.</li>
 * </ul>
 */
class ContractMirrorHashVectorTest {

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private static final String DOMAIN_ID = "5d3c0e6a-71d2-4e5b-9a64-3f8a2b1c9d70";
    private static final String CONTRACT_ID = "0f9b7c2e-4a1d-4c3b-8e5f-6a7b8c9d0e1f";
    private static final String BREACH_ID = "7e2a9c4b-3f6d-4a8e-b1c5-d9e0f1a2b3c4";
    private static final String CONTRACT_KEY = "co-tribal-knowledge-depopulation";
    private static final Instant FIXED_NOW = Instant.parse("2026-05-12T00:00:00Z");

    // ---- Pinned vector A: activation anchor, GENESIS link ---------------------------------
    private static final String EXPECTED_JSON_ACTIVATED =
            "{\"decisionType\":\"CONTRACT_ACCOUNTABILITY\","
            + "\"description\":\"Coordination contract co-tribal-knowledge-depopulation"
            + " activated: all required parties accepted.\","
            + "\"domainId\":\"" + DOMAIN_ID + "\","
            + "\"metadata\":{\"anchor\":\"CONTRACT_ACTIVATED\",\"contractId\":\"" + CONTRACT_ID
            + "\",\"contractKey\":\"" + CONTRACT_KEY
            + "\",\"occurredAt\":\"2026-05-12T00:00:00Z\"},"
            + "\"previousHash\":\"GENESIS\","
            + "\"status\":\"APPROVED\","
            + "\"title\":\"contract:co-tribal-knowledge-depopulation:CONTRACT_ACTIVATED\"}";
    private static final String EXPECTED_HASH_ACTIVATED =
            "ee1fb02005d2cbfa220a19f4eea8346830183b67a194b03b6009a4864e507b65";

    // ---- Pinned vector B: decline anchor, links to A ---------------------------------------
    private static final String EXPECTED_JSON_DECLINED =
            "{\"decisionType\":\"CONTRACT_ACCOUNTABILITY\","
            + "\"description\":\"Coordination contract co-tribal-knowledge-depopulation"
            + " resolved DECLINED: a legitimate first-class terminal resolution, never a"
            + " violation.\","
            + "\"domainId\":\"" + DOMAIN_ID + "\","
            + "\"metadata\":{\"anchor\":\"CONTRACT_DECLINED\",\"contractId\":\"" + CONTRACT_ID
            + "\",\"contractKey\":\"" + CONTRACT_KEY
            + "\",\"occurredAt\":\"2026-05-12T00:00:00Z\"},"
            + "\"previousHash\":\"" + EXPECTED_HASH_ACTIVATED + "\","
            + "\"status\":\"APPROVED\","
            + "\"title\":\"contract:co-tribal-knowledge-depopulation:CONTRACT_DECLINED\"}";
    private static final String EXPECTED_HASH_DECLINED =
            "24c0ed5aa0ee4f35f37fd1ded3de903c1876cbdd2efbed3f858c8575722f58e2";

    // ---- Pinned vector C: waiver anchor (full metadata), links to B ------------------------
    private static final String EXPECTED_JSON_WAIVED =
            "{\"decisionType\":\"CONTRACT_ACCOUNTABILITY\","
            + "\"description\":\"Breach " + BREACH_ID + " on coordination contract"
            + " co-tribal-knowledge-depopulation waived by a human actor (ADR D16);"
            + " rationale recorded in contract_events.\","
            + "\"domainId\":\"" + DOMAIN_ID + "\","
            + "\"metadata\":{\"anchor\":\"BREACH_WAIVED\",\"contractId\":\"" + CONTRACT_ID
            + "\",\"contractKey\":\"" + CONTRACT_KEY
            + "\",\"breachId\":\"" + BREACH_ID + "\",\"periodKey\":\"2026-04\","
            + "\"resolutionActor\":\"Operating Partner\","
            + "\"occurredAt\":\"2026-05-12T00:00:00Z\"},"
            + "\"previousHash\":\"" + EXPECTED_HASH_DECLINED + "\","
            + "\"status\":\"APPROVED\","
            + "\"title\":\"contract:co-tribal-knowledge-depopulation:BREACH_WAIVED\"}";
    private static final String EXPECTED_HASH_WAIVED =
            "a8654138c12f655b6f27d8ef2bb5d5f2920c546b5bc3a4301065af5ca1442b59";

    private DesignDecisionRepository repository;
    private DecisionLogService decisionLogService;
    private DecisionLogContractAccountabilityMirror mirror;
    private List<DesignDecision> chain;

    @BeforeEach
    void setUp() {
        repository = mock(DesignDecisionRepository.class);
        PlatformTransactionManager txManager = mock(PlatformTransactionManager.class);
        when(txManager.getTransaction(any())).thenReturn(new SimpleTransactionStatus());
        chain = new ArrayList<>();
        when(repository.save(any(DesignDecision.class))).thenAnswer(inv -> {
            DesignDecision d = inv.getArgument(0);
            chain.add(d);
            return d;
        });
        when(repository.findByDomainId(UUID.fromString(DOMAIN_ID)))
                .thenAnswer(inv -> new ArrayList<>(chain));
        decisionLogService = new DecisionLogService(repository, new ObjectMapper(), txManager);
        mirror = new DecisionLogContractAccountabilityMirror(
                decisionLogService, Clock.fixed(FIXED_NOW, ZoneOffset.UTC), MAPPER);
    }

    /**
     * The full activation → decline → waiver sequence reproduces the pinned
     * chain GENESIS → A → B → C byte-for-byte (no transaction active here ⇒
     * the mirror appends immediately). {@code currentHash} equality IS the
     * canonical-JSON byte pin: the hash is SHA-256 over those exact bytes
     * (algorithm itself pinned by {@code CanonicalJsonHashVectorTest}), and
     * {@link #pinnedHashes_agreeWithIndependentDigest()} proves the pinned
     * constants really are the digests of the pinned JSON strings.
     */
    @Test
    void anchorSequence_reproducesPinnedChain() {
        mirror.onActivated(contract());
        mirror.onDeclined(contract());
        mirror.onBreachWaived(contract(), breach());

        assertThat(chain).hasSize(3);

        DesignDecision activated = chain.get(0);
        assertThat(activated.getPreviousHash()).isEqualTo("GENESIS");
        assertThat(activated.getCurrentHash()).isEqualTo(EXPECTED_HASH_ACTIVATED);

        DesignDecision declined = chain.get(1);
        assertThat(declined.getPreviousHash()).isEqualTo(EXPECTED_HASH_ACTIVATED);
        assertThat(declined.getCurrentHash()).isEqualTo(EXPECTED_HASH_DECLINED);

        DesignDecision waived = chain.get(2);
        assertThat(waived.getPreviousHash()).isEqualTo(EXPECTED_HASH_DECLINED);
        assertThat(waived.getCurrentHash()).isEqualTo(EXPECTED_HASH_WAIVED);
    }

    /** The pinned hashes agree with an independent JDK digest of the pinned JSON bytes. */
    @Test
    void pinnedHashes_agreeWithIndependentDigest() throws Exception {
        assertThat(independentSha256(EXPECTED_JSON_ACTIVATED))
                .isEqualTo(EXPECTED_HASH_ACTIVATED);
        assertThat(independentSha256(EXPECTED_JSON_DECLINED))
                .isEqualTo(EXPECTED_HASH_DECLINED);
        assertThat(independentSha256(EXPECTED_JSON_WAIVED))
                .isEqualTo(EXPECTED_HASH_WAIVED);
    }

    private static String independentSha256(String input) throws Exception {
        java.security.MessageDigest digest = java.security.MessageDigest.getInstance("SHA-256");
        byte[] bytes = digest.digest(input.getBytes(java.nio.charset.StandardCharsets.UTF_8));
        StringBuilder sb = new StringBuilder(bytes.length * 2);
        for (byte b : bytes) {
            sb.append(String.format("%02x", b));
        }
        return sb.toString();
    }

    /** Waiver metadata omits the null-valued optional keys rather than writing JSON nulls. */
    @Test
    void waiverAnchor_omitsNullPeriodKeyAndActor() {
        ContractBreach bare = breach();
        bare.setPeriodKey(null);
        bare.setResolutionActor(null);
        mirror.onBreachWaived(contract(), bare);

        DesignDecision anchor = chain.get(0);
        assertThat(anchor.getMetadata().has("periodKey")).isFalse();
        assertThat(anchor.getMetadata().has("resolutionActor")).isFalse();
        assertThat(anchor.getMetadata().get("breachId").asText()).isEqualTo(BREACH_ID);
    }

    /** Anchor content sanity: immutable identifiers only — never the display title. */
    @Test
    void anchors_referenceContractKeyNeverDisplayTitle() {
        mirror.onActivated(contract());
        DesignDecision anchor = chain.get(0);
        assertThat(anchor.getDecisionType()).isEqualTo(DecisionType.CONTRACT_ACCOUNTABILITY);
        assertThat(anchor.getStatus()).isEqualTo(DecisionStatus.APPROVED);
        assertThat(anchor.getTitle()).doesNotContain("Tribal-knowledge depopulation");
        assertThat(anchor.getDescription()).doesNotContain("Tribal-knowledge depopulation");
        assertThat(anchor.getTitle()).contains(CONTRACT_KEY);
    }

    // ------------------------------------------------------------------ fixtures

    private static Contract contract() {
        Contract c = new Contract();
        c.setId(UUID.fromString(CONTRACT_ID));
        c.setDomainId(UUID.fromString(DOMAIN_ID));
        c.setContractKey(CONTRACT_KEY);
        c.setContractType("cross-portfolio-opportunity");
        // Display title deliberately present so the never-in-chain pin is meaningful.
        c.setTitle("Tribal-knowledge depopulation across four healthcare/insurance subs");
        c.setStatus(ContractStatus.ACTIVE);
        c.setProposedAt(Instant.parse("2026-04-01T00:00:00Z"));
        c.setProposedBy("Beacon Corporate Operations");
        return c;
    }

    private static ContractBreach breach() {
        ContractBreach b = new ContractBreach();
        b.setId(UUID.fromString(BREACH_ID));
        b.setContractId(UUID.fromString(CONTRACT_ID));
        b.setPeriodKey("2026-04");
        b.setStatus(BreachStatus.WAIVED);
        b.setResolution(BreachResolution.WAIVED);
        b.setResolutionActor("Operating Partner");
        b.setSummary("Missing attestation for period 2026-04");
        b.setDetectedAt(Instant.parse("2026-05-09T00:00:00Z"));
        b.setDetectedBy(BreachDetectedBy.MONITOR);
        return b;
    }
}
